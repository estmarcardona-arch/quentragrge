const fs = require('fs');

const markdown = fs.readFileSync('matrix.md', 'utf-8');
const lines = markdown.trim().split('\n');

const rolesLine = lines[0].split('|').map(s => s.trim()).filter(Boolean);
rolesLine.shift(); // Remove 'Módulo' header
const roles = rolesLine.map(r => r.toLowerCase());

// Define permission IDs corresponding to the modules in order
const permissionIds = [
  'brief',
  'formula',
  'prototipos',
  'solicitudes_op',
  'recepcion',
  'liberacion_insumos',
  'orden_produccion',
  'ejecucion_lote',
  'resultados_cc',
  'desviaciones',
  'liberacion_final',
  'paquete_tecnico',
  'trazabilidad',
  'usuarios_catalogos',
  'plantillas',
  'bodegas',
  'traslados',
  'sgd',
  'capacitacion'
];

let sql = `-- MIGRATION: 0004_seed_permissions.sql\n-- Autogenerated from PRD section 2.2\n\n`;
sql += `DELETE FROM role_permissions;\n\n`; // Clear previous partial inserts

const rows = lines.slice(2);
rows.forEach((row, rowIndex) => {
  const cols = row.split('|').map(s => s.trim()).filter(Boolean);
  const moduleName = cols.shift();
  const permId = permissionIds[rowIndex];

  cols.forEach((cell, roleIndex) => {
    const role = roles[roleIndex];
    if (cell !== '—') {
      // Find matches for L, C, F, A (ignoring parenthetical text)
      // We look for independent letters L, C, F, A
      const letters = new Set();
      // Regex to find independent L, C, F, A not inside parens (we can just strip parens first)
      const cleanCell = cell.replace(/\(.*?\)/g, '');
      const matches = cleanCell.match(/\b([LCFA])\b/g);
      if (matches) {
        matches.forEach(m => letters.add(m));
      }

      Array.from(letters).forEach(level => {
        sql += `INSERT INTO role_permissions (role, permission_id, access_level) VALUES ('${role}', '${permId}', '${level}') ON CONFLICT DO NOTHING;\n`;
      });
    }
  });
});

fs.writeFileSync('supabase/migrations/20261007000004_seed_permissions.sql', sql);
console.log('SQL generated successfully.');
